/**
 * Self-host the web fonts instead of loading them from Google's CDN.
 *
 *   node scripts/self-host-fonts.mjs
 *
 * Replaces the render-blocking `@import url('https://fonts.googleapis.com/...')`
 * in src/index.css. All three families — Marcellus, Inter and JetBrains Mono —
 * are licensed under the SIL Open Font License, which permits self-hosting.
 *
 * Downloads only the `latin` and `latin-ext` subsets: the site is English-only,
 * and `unicode-range` means a browser fetches a subset file only when it needs
 * it. Writes public/fonts/*.woff2 plus a generated src/fonts.css.
 */

import { writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const fontsDir = path.join(root, 'public', 'fonts');

/** The exact Google Fonts request the site used before self-hosting. */
const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Marcellus&family=Inter:wght@300;400;500;600&family=JetBrains+Mono&display=swap';

const USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

/** Subsets to keep. Everything else (cyrillic, greek, vietnamese) is dropped. */
const KEEP_SUBSETS = new Set(['latin', 'latin-ext']);

function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

async function fetchText(url) {
  const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
  if (!response.ok) throw new Error(`GET ${url} -> ${response.status}`);
  return response.text();
}

async function fetchBinary(url) {
  const response = await fetch(url, { headers: { 'User-Agent': USER_AGENT } });
  if (!response.ok) throw new Error(`GET ${url} -> ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

/**
 * Google Fonts emits `/* subset *\/` comments before each @font-face block.
 * Walk the stylesheet and pair each block with the subset that precedes it.
 */
function parseFontFaces(css) {
  const faces = [];
  const pattern = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/gi;

  for (const match of css.matchAll(pattern)) {
    const subset = match[1];
    const body = match[2];
    const read = key => body.match(new RegExp(`${key}\\s*:\\s*([^;]+);`))?.[1]?.trim();

    const family = read('font-family')?.replace(/['"]/g, '');
    const weight = read('font-weight');
    const src = read('src')?.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
    const unicodeRange = read('unicode-range');
    const fontStyle = read('font-style') ?? 'normal';
    const display = read('font-display') ?? 'swap';

    if (!family || !weight || !src) continue;
    faces.push({ family, weight, src, unicodeRange, fontStyle, display, subset });
  }

  return faces;
}

async function run() {
  console.log('Fetching the Google Fonts stylesheet ...');
  const css = await fetchText(CSS_URL);
  const faces = parseFontFaces(css);
  console.log(`  ${faces.length} @font-face blocks found`);

  const keep = faces.filter(face => KEEP_SUBSETS.has(face.subset));
  console.log(`  keeping ${keep.length} blocks for subsets: ${[...KEEP_SUBSETS].join(', ')}`);

  await mkdir(fontsDir, { recursive: true });

  const rules = [];
  let totalBytes = 0;

  for (const face of keep) {
    const fileName = `${slug(face.family)}-${face.weight}-${face.subset}.woff2`;
    const buffer = await fetchBinary(face.src);
    await writeFile(path.join(fontsDir, fileName), buffer);
    totalBytes += buffer.length;
    console.log(`  ${fileName}  ${(buffer.length / 1024).toFixed(1)} KB`);

    rules.push(
      [
        '@font-face {',
        `  font-family: '${face.family}';`,
        `  font-style: ${face.fontStyle};`,
        `  font-weight: ${face.weight};`,
        `  font-display: ${face.display};`,
        `  src: url('/fonts/${fileName}') format('woff2');`,
        face.unicodeRange ? `  unicode-range: ${face.unicodeRange};` : null,
        '}'
      ]
        .filter(Boolean)
        .join('\n')
    );
  }

  const header = [
    '/*',
    ' * GENERATED by scripts/self-host-fonts.mjs — do not edit by hand.',
    ' *',
    ' * Self-hosted so the site does not depend on a third-party font CDN',
    ' * (which was a render-blocking @import and required a CSP allowance).',
    ' * Marcellus, Inter and JetBrains Mono are licensed under the SIL Open',
    ' * Font License, which permits self-hosting.',
    ' *',
    ` * Source: ${CSS_URL}`,
    ' */',
    ''
  ].join('\n');

  const outputPath = path.join(root, 'src', 'fonts.css');
  await writeFile(outputPath, `${header}${rules.join('\n\n')}\n`, 'utf8');

  console.log('');
  console.log(`Fonts:    ${keep.length} files, ${(totalBytes / 1024).toFixed(1)} KB total`);
  console.log(`Written:  public/fonts/*.woff2 and src/fonts.css`);
}

run().catch(error => {
  console.error('Font self-hosting failed:', error);
  process.exitCode = 1;
});
